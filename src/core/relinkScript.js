'use strict';

// An ExtendScript that ships inside packages. If After Effects cannot find
// the footage after the package is extracted somewhere else, running this
// script relinks every item to the files next to the project.

/**
 * @param {{from: string, to: string, rel: string, sequence: boolean}[]} entries
 */
function relinkScript(projectName, entries) {
  // JSON is valid ES3 literal syntax; escape the two line separators that are not.
  const data = JSON.stringify(entries)
    .split(String.fromCharCode(0x2028))
    .join('\\' + 'u2028')
    .split(String.fromCharCode(0x2029))
    .join('\\' + 'u2029');
  return `// Relink Footage — generated by Cargo for "${projectName.replace(/[\r\n"]/g, ' ')}"
// In After Effects: open the packaged project, then choose
// File > Scripts > Run Script File... and pick this file.
(function () {
    var ENTRIES = ${data};

    if (!app.project || !app.project.file) {
        alert("Open (or save) the packaged project first, then run this script again.");
        return;
    }
    var root = app.project.file.parent;
    function norm(p) { return String(p).replace(/\\\\/g, "/").toLowerCase(); }

    var lookup = {};
    for (var i = 0; i < ENTRIES.length; i++) {
        lookup[norm(ENTRIES[i].from)] = ENTRIES[i];
        lookup[norm(ENTRIES[i].to)] = ENTRIES[i];
    }

    function currentPath(src) {
        try { if (src.missingFootagePath) { return src.missingFootagePath; } } catch (e) {}
        try { if (src.file) { return src.file.fsName; } } catch (e2) {}
        return null;
    }

    app.beginUndoGroup("Relink Footage (Cargo)");
    var relinked = 0, ok = 0, failed = [];
    for (var j = 1; j <= app.project.numItems; j++) {
        var item = app.project.item(j);
        if (!(item instanceof FootageItem)) { continue; }
        var src = item.mainSource;
        if (!(src instanceof FileSource)) { continue; }
        var current = currentPath(src);
        if (!current) { continue; }
        var entry = lookup[norm(current)];
        if (!entry) { continue; }
        var target = new File(root.fsName + "/" + entry.rel);
        if (!target.exists) { failed.push(item.name); continue; }
        if (!item.footageMissing && norm(target.fsName) === norm(current)) { ok++; continue; }
        try {
            if (entry.sequence) { item.replaceWithSequence(target, false); }
            else { item.replace(target); }
            relinked++;
        } catch (err) {
            failed.push(item.name);
        }
    }
    app.endUndoGroup();

    var msg = "Relinked " + relinked + " item(s).";
    if (ok) { msg += "\\n" + ok + " item(s) were already linked."; }
    if (failed.length) {
        msg += "\\n\\nCould not relink " + failed.length + ":\\n" + failed.slice(0, 15).join("\\n");
        if (failed.length > 15) { msg += "\\n…"; }
    }
    alert(msg, "Cargo");
})();
`;
}

module.exports = { relinkScript };
